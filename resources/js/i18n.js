const dictionaries = { en, km };

const MONTHS = {
    en: ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'],
    enLong: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'],
    km: ['មករា', 'កុម្ភៈ', 'មីនា', 'មេសា', 'ឧសភា', 'មិថុនា', 'កក្កដា', 'សីហា', 'កញ្ញា', 'តុលា', 'វិច្ឆិកា', 'ធ្នូ'],
};

export function getLocale() {
    const locale = typeof document !== 'undefined' ? document.body?.dataset.locale : 'en';
    return locale === 'km' ? 'km' : 'en';
}

export function t(key, vars = {}) {
    const locale = getLocale();
    const dictionary = dictionaries[locale];
    const singular = vars.count === 1 ? `${key}.one` : null;

    let text = (singular && dictionary[singular]) || dictionary[key]
        || (singular && en[singular]) || en[key] || key;

    Object.entries(vars).forEach(([name, value]) => {
        text = text.split(`{${name}}`).join(String(value));
    });

    return text;
}

// 1..12 -> "Mar" / "March" / "មីនា"
export function monthName(month, long = false) {
    const locale = getLocale();
    if (locale === 'km') return MONTHS.km[month - 1];
    return (long ? MONTHS.enLong : MONTHS.en)[month - 1];
}

// "2026-03" -> "Mar 26" (short) or "March 2026" (long)
export function formatMonth(value, long = false) {
    const [year, month] = String(value).split('-').map(Number);
    if (!year || !month) return value;
    return long ? `${monthName(month, true)} ${year}` : `${monthName(month)} ${String(year).slice(2)}`;
}

const WEEKDAYS = {
    en: ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'],
    km: ['អាទិត្យ', 'ចន្ទ', 'អង្គារ', 'ពុធ', 'ព្រហ', 'សុក្រ', 'សៅរ៍'],
};

// "2026-10-06" -> "6 Tue" / "6 អង្គារ". Spelled out because browsers' Intl has no Khmer day names and falls back to English.
export function formatDay(value) {
    const date = new Date(`${value}T00:00:00`);
    return `${date.getDate()} ${WEEKDAYS[getLocale()][date.getDay()]}`;
}

let provincesKm = null;

// Province object or { name } -> its Khmer name when the page is in Khmer.
export function provinceName(province) {
    if (!province) return '';
    if (getLocale() !== 'km') return province.name;
    if (province.km) return province.km;

    if (provincesKm === null) {
        try {
            provincesKm = JSON.parse(document.body.dataset.provincesKm || '{}');
        } catch {
            provincesKm = {};
        }
    }

    return provincesKm[province.name] || province.name;
}
